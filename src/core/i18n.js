/** @returns {string} */
function detect() {
  const stored = load('lang', null);
  if (stored && LANGS.includes(stored)) return stored;
  let tags = [];
  try {
    tags = (navigator.languages && navigator.languages.length
      ? navigator.languages
      : [navigator.language || 'en']).map((t) => String(t).toLowerCase());
  } catch {
    tags = ['en'];
  }
  for (const tag of tags) {
    if (tag.startsWith('pt')) return 'pt';
    if (tag.startsWith('es')) return 'es';
    if (tag.startsWith('en')) return 'en';
  }
  return 'en';
}

let current = detect();

/** @type {Set<()=>void>} */
const listeners = new Set();

/** @returns {string} */
export function getLang() {
  return current;
}

/** @param {string} lang */
export function setLang(lang) {
  if (!LANGS.includes(lang) || lang === current) return;
  current = lang;
  save('lang', lang);
  for (const fn of listeners) fn();
}

/** @param {()=>void} fn @returns {()=>void} */
export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/**
 * @param {string} key
 * @param {...(string|number)} args substituem {0}, {1}, ...
 * @returns {string}
 */
export function t(key, ...args) {
  const table = STRINGS[current] || STRINGS.en;
  let value = table[key];
  if (value === undefined) value = STRINGS.en[key];
  if (value === undefined) return key;
  if (!args.length) return value;
  return value.replace(/\{(\d+)\}/g, (m, i) => {
    const v = args[Number(i)];
    return v === undefined ? m : String(v);
  });
}
